/**
 * Heuristic list of block-name fragments that are essentially always player-placed (manufactured
 * building/decoration blocks, furniture, redstone components) rather than raw resources you'd
 * find by mining terrain. Used to stop `collectBlock` from being pointed at a house, chest, or
 * other build instead of an actual resource — it's not exhaustive, just a practical safety net.
 */
